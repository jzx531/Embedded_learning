/******************************************************************************
#define LCD_CTRL   	  	  GPIOB		//定义TFT 数据端口

#define LCD_CTRL2   	  	GPIOA		//定义BLK 数据端口

#define LCD_BLK        	GPIO_Pin_8   //PA8--BLK
#define LCD_RS         	GPIO_Pin_1	 //PB11---RS/DC
#define LCD_CS        	GPIO_Pin_12  //PB11---CS/CE

#define LCD_SCL        	GPIO_Pin_13	 //PB13--SCL/SCK
#define LCD_SDA        	GPIO_Pin_15	 //PB15 --SDA/DIN

#define LCD_SDO         GPIO_Pin_14  //PB14----SDO

*******************************************************************************/


//液晶IO初始化配置
void LCD_GPIO_Init(void)
{

	 GPIO_InitTypeDef GPIO_InitStruct = {0};

  __HAL_RCC_GPIOA_CLK_ENABLE();
  __HAL_RCC_GPIOB_CLK_ENABLE();

  //Configure GPIO pin Output Level 
  HAL_GPIO_WritePin(GPIOB, GPIO_PIN_1|GPIO_PIN_12|GPIO_PIN_13|GPIO_PIN_14
                          |GPIO_PIN_15, GPIO_PIN_RESET);

  //Configure GPIO pin Output Level 
  HAL_GPIO_WritePin(GPIOA, GPIO_PIN_8, GPIO_PIN_RESET);


  //Configure GPIO pins : PB1 PB12 PB13 PB14 PB15 
                           
  GPIO_InitStruct.Pin = GPIO_PIN_1|GPIO_PIN_12|GPIO_PIN_13|GPIO_PIN_14
                          |GPIO_PIN_15;
  GPIO_InitStruct.Mode = GPIO_MODE_OUTPUT_PP;
  GPIO_InitStruct.Pull = GPIO_NOPULL;
  GPIO_InitStruct.Speed = GPIO_SPEED_FREQ_HIGH;
  HAL_GPIO_Init(GPIOB, &GPIO_InitStruct);

  //Configure GPIO pin : PA8 
  GPIO_InitStruct.Pin = GPIO_PIN_8;
  GPIO_InitStruct.Mode = GPIO_MODE_OUTPUT_PP;
  GPIO_InitStruct.Pull = GPIO_NOPULL;
  GPIO_InitStruct.Speed = GPIO_SPEED_FREQ_HIGH;
  HAL_GPIO_Init(GPIOA, &GPIO_InitStruct);
	
	

	
	LCD_SDO_SET;//设置数据输出引脚为高
	LCD_BLK_SET;//开背光
  LCD_BLK_CLR;//关背光
	LCD_BLK_SET;//开背光
	
}
//向SPI总线传输一个8位数据
void  SPI_WriteData(u8 Data)
{
	unsigned char i=0;
	for(i=8;i>0;i--)
	{
		if(Data&0x80)	
	  LCD_SDA_SET; //输出数据
      else LCD_SDA_CLR;
	   
      LCD_SCL_CLR;       
      LCD_SCL_SET;
      Data<<=1; 
	}
}

//向液晶屏写一个8位指令
void Lcd_WriteIndex(u8 Index)
{
   //SPI 写命令时序开始
   LCD_CS_CLR;
   LCD_RS_CLR;
	 SPI_WriteData(Index);
   LCD_CS_SET;
}

//向液晶屏写一个8位数据
void Lcd_WriteData(u8 Data)
{
   LCD_CS_CLR;
   LCD_RS_SET;
   SPI_WriteData(Data);
   LCD_CS_SET; 
}
//向液晶屏写一个16位数据
void LCD_WriteData_16Bit(u16 Data)
{
   LCD_CS_CLR;
   LCD_RS_SET;
	 SPI_WriteData(Data>>8); 	//写入高8位数据
	 SPI_WriteData(Data); 			//写入低8位数据
   LCD_CS_SET; 
}

void Lcd_WriteReg(u8 Index,u8 Data)
{
	Lcd_WriteIndex(Index);
  Lcd_WriteData(Data);
}

void Lcd_Reset(void)
{
	LCD_RS_CLR;

	delay_ms(100);
	//HAL_Delay(100);

	LCD_RS_SET;
	delay_ms(50);
	//HAL_Delay(50);
	

	
}

